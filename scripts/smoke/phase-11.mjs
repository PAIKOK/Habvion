import { sampleHouse } from "./helpers.mjs";
export default async function ({ page, url, check }) {
  const refused = await sampleHouse(page, url);
  check("sample house builds", refused.length === 0, refused.join(" | "));
  await page.getByRole("button", { name: "3D", exact: true }).first().click();
  await page.locator('[data-testid="scene-3d"] canvas').waitFor();
  await page.getByRole("toolbar", { name: "3D view" }).getByRole("button", { name: "Walk" }).click();
  await page.waitForFunction(() => window.__hbWalk);
  const start = await page.evaluate(() => window.__hbWalk);
  check("walk starts outside the front door", start.y < 6, JSON.stringify(start));
  const map = page.getByTestId("walk-minimap"), marker = page.getByTestId("walk-map-player");
  await marker.waitFor();
  check("walk mode has a visible navigation mini-map", await map.isVisible() && await page.getByTestId("walk-map-plan").isVisible());
  check("the entrance location is labelled outside", (await page.getByTestId("walk-current-room").innerText()).includes("Outside"));
  check("the compass follows the camera direction", /Facing S/.test(await map.innerText()));
  const initialMarker = Number(await marker.getAttribute("data-y"));
  await page.screenshot({ path: "artifacts/phase-11-entrance.png" });
  await page.keyboard.down("KeyW");
  await page.waitForTimeout(1600);
  await page.keyboard.up("KeyW");
  const inside = await page.evaluate(() => window.__hbWalk);
  check("W walks in through the door onto the plinth", inside.y > 8 && Math.abs(inside.feet - 0.75) < 0.01, JSON.stringify(inside));
  await page.waitForFunction(() => document.querySelector('[data-testid="walk-current-room"]')?.getAttribute("data-room-id") === "liv");
  check("the location label updates to Living after entering", /Living/.test(await page.getByTestId("walk-current-room").innerText()));
  check("the player marker moves with the walker", Number(await marker.getAttribute("data-y")) > initialMarker + 2);
  check("the current room is highlighted on the map", await map.locator('rect[data-room-id="liv"][data-current="true"]').count() === 1);
  await page.screenshot({ path: "artifacts/phase-11-inside.png" });
  await page.keyboard.down("KeyW");
  await page.waitForTimeout(4000);
  await page.keyboard.up("KeyW");
  const stopped = await page.evaluate(() => window.__hbWalk);
  check("the coffee table or sofa stops you before the far wall", stopped.y < 19.5, JSON.stringify(stopped));
  check("walk hint is shown", await page.getByText("WASD to walk").isVisible());
  await map.getByRole("button", { name: "Hide mini-map" }).click();
  check("map controls do not capture the mouse", await page.evaluate(() => document.pointerLockElement === null));
  check("the map collapses but the room label stays visible", (await page.getByTestId("walk-map-plan").count()) === 0 && await page.getByTestId("walk-current-room").isVisible());
  await map.getByRole("button", { name: "Show mini-map" }).click();
  check("the map can be expanded again", await page.getByTestId("walk-map-plan").isVisible());
  await page.getByRole("toolbar", { name: "3D view" }).getByRole("button", { name: "3D", exact: true }).click();
  check("the mini-map is only shown in walk mode", (await page.getByTestId("walk-minimap").count()) === 0);
}
