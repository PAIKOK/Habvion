export default async function ({ page, url, check }) {
  const email = `p13-${Date.now()}@homebuilder.test`;
  await page.context().clearCookies();
  await page.goto(url + "/start", { waitUntil: "networkidle" });
  await page.waitForURL("**/login?next=%2Fstart");
  check("a stranger is sent from /start to log in", new URL(page.url()).pathname === "/login");
  await page.goto(url + "/editor", { waitUntil: "networkidle" });
  check("/editor is protected too", new URL(page.url()).pathname === "/login");
  const googleId = (await (await page.request.get(`${url}/api/auth/config`)).json()).googleClientId;
  if (googleId) check("log in offers 'Continue with Google' (it loads once clicked, per the cookie choice)", await page.getByTestId("google-consent").isEnabled());
  else check("Google button reports itself unavailable without a client id", await page.getByRole("button", { name: /Continue with Google — not available/ }).isDisabled());
  await page.screenshot({ path: "artifacts/phase-13-login.png" });

  await page.goto(url + "/", { waitUntil: "networkidle" });
  await page.getByRole("link", { name: "Start building" }).first().click();
  await page.waitForURL("**/signup?next=%2Fstart");
  check("Start building leads strangers to sign up first", new URL(page.url()).pathname === "/signup");
  await page.getByLabel("Name").fill("Priya Nair");
  await page.getByLabel("Email").fill(email);
  await page.getByLabel(/^Password/).fill("short");
  await page.getByRole("button", { name: "Create account" }).click();
  check("a short password is explained beside the field", (await page.locator("#auth-password-error").innerText()).includes("10 characters"));
  check("…the field is marked invalid", (await page.getByLabel(/^Password/).getAttribute("aria-invalid")) === "true");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-invalid") === "true", null, { timeout: 3000 }).catch(() => {});
  const focused = await page.evaluate(() => document.activeElement?.getAttribute("data-testid") ?? document.activeElement?.outerHTML.slice(0, 120));
  check("…and focus goes to the first problem on the page, the agreement box", focused === "signup-consent", focused);
  check("…and a summary is announced", /highlighted field/.test(await page.getByRole("alert").innerText()));
  await page.getByRole("button", { name: "Show password" }).click();
  check("the password can be shown", (await page.getByLabel(/^Password/).getAttribute("type")) === "text");
  await page.getByRole("button", { name: "Hide password" }).click();
  check("…and hidden again", (await page.getByLabel(/^Password/).getAttribute("type")) === "password");
  await page.screenshot({ path: "artifacts/phase-13-signup.png" });
  await page.getByLabel(/^Password/).fill("a long enough password");
  await page.getByRole("button", { name: "Create account" }).click();
  check("the password error clears once fixed", (await page.locator("#auth-password-error").count()) === 0);
  check("sign-up asks for the age and terms agreement", (await page.locator("#auth-consent-error").innerText()).includes("18 or older"));
  check("Google sign-up is locked until the box is ticked", (await page.getByTestId("google-locked").count()) === 1 || (await page.getByText(/not available/).count()) === 1);
  await page.getByTestId("signup-consent").check();
  await page.getByRole("button", { name: "Create account" }).click();
  await page.waitForURL("**/start");
  check("signup returns to where they were going", new URL(page.url()).pathname === "/start");
  check("header shows who is signed in", (await page.getByTestId("account").innerText()).includes("Priya Nair"));
  const cookies = await page.context().cookies();
  const session = cookies.find((c) => c.name === "hb_session");
  check("session cookie is httpOnly and Lax", !!session && session.httpOnly && session.sameSite === "Lax");
  check("page script cannot read the session", !(await page.evaluate(() => document.cookie)).includes("hb_session"));
  await page.screenshot({ path: "artifacts/phase-13-start.png" });

  await page.reload({ waitUntil: "networkidle" });
  check("the session survives a reload", new URL(page.url()).pathname === "/start");
  await page.getByRole("button", { name: "Sign out" }).click();
  await page.waitForURL(url + "/");
  await page.goto(url + "/start", { waitUntil: "networkidle" });
  check("signing out protects /start again", new URL(page.url()).pathname === "/login");

  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Password", { exact: true }).fill("the wrong password");
  await page.getByRole("button", { name: "Log in" }).click();
  check("a wrong password is refused politely", (await page.getByRole("alert").innerText()).includes("incorrect"));
  await page.getByLabel("Password", { exact: true }).fill("a long enough password");
  await page.getByRole("button", { name: "Log in" }).click();
  await page.waitForURL("**/start");
  check("logging in returns to /start", new URL(page.url()).pathname === "/start");
  await page.goto(url + "/login?next=https://evil.example", { waitUntil: "networkidle" });
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Password", { exact: true }).fill("a long enough password");
  await page.getByRole("button", { name: "Log in" }).click();
  await page.waitForURL("**/start");
  check("an off-site next= is ignored", new URL(page.url()).origin === new URL(url).origin);
}
