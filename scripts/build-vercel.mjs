import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));

// Vercel's Node runtime does not resolve tsconfig path aliases. Bundle our own
// server/shared code first; leave ordinary runtime packages for Vercel to trace.
const result = await build({
  absWorkingDir: root,
  entryPoints: ["server/src/vercel/handler.ts"],
  outfile: ".generated/vercel-handler.mjs",
  tsconfig: "server/tsconfig.json",
  platform: "node",
  format: "esm",
  target: "node24",
  bundle: true,
  metafile: true,
  external: ["express", "cors", "cookie-parser", "jose", "mongodb", "zod", "@vercel/functions"],
  logLevel: "info",
  banner: { js: "// Generated by scripts/build-vercel.mjs. Do not edit or commit." },
});

for (const output of Object.values(result.metafile.outputs)) {
  if (output.imports.some((item) => item.path.startsWith("@shared/"))) {
    throw new Error("Vercel API build contains an unresolved @shared path alias.");
  }
}
