export const CATALOG: FurnitureItem[] = ROWS.map(
  ([id, name, category, shape, width, depth, height, price, colorHex, rooms, extra]) => ({
    id,
    name,
    category,
    shape,
    width,
    depth,
    height,
    price,
    colorHex,
    suitableFor: [...new Set(rooms.split(" ").flatMap((k) => G[k] ?? [k as RoomType]))],
    mount: "floor",
    ...extra,
  }),
);
const BY_ID = new Map(CATALOG.map((i) => [i.id, i]));
export const findCatalogItem = (id: string) => BY_ID.get(id);
export function catalogItemOrThrow(id: string) {
  const item = BY_ID.get(id);
  if (!item) throw new Error(`Unknown catalog item: ${id}`);
  return item;
}
/** Design-aware lookup: the design's own imported items first, then the catalog. */
export const itemFor = (design: Pick<HomeDesign, "customItems">, id: string) =>
  design.customItems?.find((i) => i.id === id) ?? BY_ID.get(id);
export const isCatalogId = (id: string) => BY_ID.has(id);
/** Suitable for every room when the list is empty. */
export const suits = (item: FurnitureItem, type: RoomType) =>
  !item.suitableFor.length || item.suitableFor.includes(type);
/** Compact one-line-per-item listing for prompts. */
export function describeCatalog(items: FurnitureItem[] = CATALOG) {
  return items
    .map((i) => `${i.id}: ${i.name} ${i.width}×${i.depth}×${i.height}ft ${i.mount}`)
    .join("\n");
}
